"""Markdown brief + JSON writers for appstudy."""

from __future__ import annotations

import json
from pathlib import Path

from .analyze import SiteModel


def render_markdown(model: SiteModel) -> str:
    lines: list[str] = []
    lines.append(f"# Rebuild brief: {model.root_url}")
    lines.append("")
    lines.append("> Clean-room brief generated by **appstudy** from the site's public, "
                 "visible surface only. It describes what a visitor sees — never copied "
                 "code, never anything behind a login. Build your own version from this "
                 "description.")
    lines.append("")
    lines.append(f"**Pages studied:** {model.total_pages}  |  "
                 f"**Forms found:** {len(model.forms)}  |  "
                 f"**Calls to action:** {len(model.calls_to_action)}")
    lines.append("")

    lines.append("## Sitemap")
    lines.append("")
    for path in model.sitemap:
        lines.append(f"- `{path}`")
    lines.append("")

    lines.append("## Page inventory")
    lines.append("")
    lines.append("| Path | Type (heuristic) | Title | Headings | Images |")
    lines.append("|---|---|---|---|---|")
    for page in model.pages:
        lines.append(f"| `{page['path']}` | {page['type']} | {page['title']} | "
                     f"{len(page['headings'])} | {page['images']} |")
    lines.append("")

    if model.nav:
        lines.append("## Navigation")
        lines.append("")
        lines.append("Links that appear in the site's navigation, most frequent first:")
        lines.append("")
        for path in model.nav:
            lines.append(f"- `{path}`")
        lines.append("")

    if model.page_types:
        lines.append("## Page types")
        lines.append("")
        for kind, count in sorted(model.page_types.items(), key=lambda kv: -kv[1]):
            lines.append(f"- {kind}: {count} page(s)")
        lines.append("")

    if model.colors or model.fonts:
        lines.append("## Design tokens (observed)")
        lines.append("")
        if model.colors:
            lines.append("Colours seen across the site, most frequent first:")
            lines.append("")
            for color, count in model.colors:
                lines.append(f"- `{color}` — on {count} page(s)")
            lines.append("")
        if model.fonts:
            lines.append("Font stacks declared in styles:")
            lines.append("")
            for font in model.fonts:
                lines.append(f"- `{font}`")
            lines.append("")

    if model.calls_to_action:
        lines.append("## Calls to action")
        lines.append("")
        for cta in model.calls_to_action:
            lines.append(f"- {cta}")
        lines.append("")

    if model.forms:
        lines.append("## Forms to rebuild")
        lines.append("")
        for form in model.forms:
            lines.append(f"### {form['page']} — `{form['method'].upper()}` → `{form['action'] or '(same page)'}`")
            lines.append("")
            for field in form["fields"]:
                req = " *(required)*" if field["required"] else ""
                label = f" — “{field['label']}”" if field["label"] else ""
                lines.append(f"- {field['kind']} `{field['name']}` ({field['type']}){label}{req}")
            lines.append("")

    if model.shared_components:
        lines.append("## Shared components")
        lines.append("")
        for component in model.shared_components:
            lines.append(f"- {component}")
        lines.append("")

    lines.append("## What to build first")
    lines.append("")
    lines.append("1. The landing page shell: navigation, hero headings, and primary call to action.")
    lines.append("2. The shared layout (header/footer) implied by the repeated navigation.")
    lines.append("3. The forms above, in the order a visitor meets them.")
    lines.append("4. The remaining pages from the sitemap, one route at a time.")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("*Page-type labels are heuristics from paths and titles. Verify each "
                 "route by visiting it before you build.*")
    return "\n".join(lines)


def write_outputs(model: SiteModel, out_dir: str | Path) -> dict[str, Path]:
    """Write brief.md and site.json into *out_dir*; return both paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    brief_path = out / "brief.md"
    json_path = out / "site.json"
    brief_path.write_text(render_markdown(model), encoding="utf-8")
    json_path.write_text(json.dumps(model.to_dict(), indent=2, ensure_ascii=False),
                         encoding="utf-8")
    return {"brief": brief_path, "json": json_path}
